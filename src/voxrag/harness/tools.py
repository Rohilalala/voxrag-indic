#: How many recently retrieved chunks stay resolvable by id. Sized for concurrent requests
#: (fuse_top_k=12 x ~170 in-flight or just-finished queries), not for durability: this is a
#: lookup convenience for a multi-turn tool loop, never a source of truth.
CHUNK_REGISTRY_SIZE: Final[int] = 2048

#: Hard ceiling on the harness's own extractive fallback answer. Roughly two sentences of
#: Devanagari; long enough to answer, short enough that a wrong span is obviously wrong.
EXTRACTIVE_MAX_CHARS: Final[int] = 420

#: Sentence terminators across the 15 supported scripts. `danda`/`double danda` end
#: sentences in Devanagari, Bengali, Gurmukhi and Odia text; Urdu uses the Arabic full stop.
_TERMINATORS: Final[str] = ".!?।॥۔\n"  # noqa: RUF001 -- U+06D4 is Urdu's full stop, not a hyphen

#: Name reported in `Answer.model` when this file, rather than `voxrag.generate`, produced
#: the answer. It must be distinguishable in the trace: an extractive fallback answer is a
#: degraded result even though it is perfectly grounded.
EXTRACTIVE_MODEL: Final[str] = "extractive:harness-fallback"

#: User-facing text per refusal reason. NO_RELEVANT_CONTEXT deliberately reuses
