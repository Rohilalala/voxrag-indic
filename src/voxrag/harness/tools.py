async def _encode_query(query: str, trace: Trace) -> np.ndarray | None:
    """Embed the query, timing it as QUERY_EMBED. Returns None when dense is unavailable.

    Returning None rather than raising is the degraded path the lexical arm exists for: a
    missing ONNX graph should cost recall, not the whole request.
    """
    with trace.stage(StageName.QUERY_EMBED) as detail:
        try:
            embedder = await _embedder(wait=False)
            if embedder is None:
                # Cold start: the encoder is still loading in the background. Answering from
                # the lexical arm now beats blowing the whole budget waiting for weights.
                detail["loading"] = True
                trace.degrade("embedder still loading; lexical-only retrieval this request")
                return None
            vectors = await embedder.encode_async([query], is_query=True)
            detail.update(dim=int(vectors.shape[1]), model=getattr(embedder, "name", "unknown"))
            return vectors[0]
        except Exception as exc:
            detail.update(failed=True, error=f"{type(exc).__name__}: {exc}")
            trace.degrade(f"query embed failed ({type(exc).__name__}); lexical-only retrieval")
            return None


async def _lexical_only(
    query: str, lang: Lang | None, top_k: int, trace: Trace
) -> list[ScoredChunk]:
    """Retrieval with the dense arm removed. Emits the same stage shape as the hybrid path
    (dense skipped, lexical timed, fuse recorded) so the latency report stays comparable."""
    from voxrag.store.hybrid import reciprocal_rank_fusion

    trace.skip(StageName.RETRIEVE_DENSE, "embedder unavailable")
    hits: list[ScoredChunk] = []
    with trace.stage(StageName.RETRIEVE_LEXICAL) as detail:
        if settings.enable_lexical:
            try:
                from voxrag.store.bm25 import get_bm25_index

                index = await asyncio.to_thread(get_bm25_index)
                hits = await with_timeout(
                    # BM25 scoring is a CPU-bound pass over a sparse matrix; inline it and
                    # the event loop stalls for every other in-flight request.
                    asyncio.to_thread(
                        index.search, query, top_k=settings.lexical_top_k, lang=lang
                    ),
                    stage_budget_ms(StageName.RETRIEVE_LEXICAL),
                    StageName.RETRIEVE_LEXICAL,
                )
            except Exception as exc:
                detail.update(failed=True, error=f"{type(exc).__name__}: {exc}")
                trace.degrade(f"lexical-only retrieval failed ({type(exc).__name__})")
        else:
            detail["disabled"] = True
        detail["candidates"] = len(hits)

    with trace.stage(StageName.FUSE) as detail:
        # Fusing against an empty dense list keeps the ScoredChunk provenance fields
        # (lexical_rank, lexical_score) populated exactly as the hybrid path would.
        fused = reciprocal_rank_fusion([], hits)[:top_k]
        detail.update(dense=0, lexical=len(hits), fused=len(fused), returned=len(fused), degraded=True)
    return fused


async def _handle_retrieve(payload: RetrieveInput, trace: Trace, ctx: Any) -> RetrievalResult:
    from voxrag.store.hybrid import get_hybrid_retriever, normalized_confidence

    vector = await _encode_query(payload.query, trace)
    if vector is None:
        hits = await _lexical_only(payload.query, payload.lang, payload.top_k, trace)
        note = "dense arm unavailable; served from the lexical index alone"
    else:
        retriever = get_hybrid_retriever()
        hits = await retriever.retrieve(
            payload.query, vector, trace=trace, lang=payload.lang, top_k=payload.top_k
        )
        note = ""

    _REGISTRY.put_many(hits)
    return RetrievalResult(
        chunks=hits,
        confidence=normalized_confidence(hits),
        n_candidates=len(hits),
        degraded=bool(note),
        note=note,
    )


def _resolve_chunks(chunk_ids: Sequence[str], ctx: Any) -> list[ScoredChunk]:
    """Map ids back to chunks: caller-supplied context first, registry second.

    The caller's context wins because it is the exact result set of *this* request; the
    registry is a shared cache and, under concurrency, could hold a same-id chunk from a
    different strategy or a rebuilt index.
    """
    supplied: dict[str, ScoredChunk] = {}
    if ctx:
        items = ctx.values() if isinstance(ctx, Mapping) else ctx
        try:
            for scored in items:
                if isinstance(scored, ScoredChunk):
                    supplied[scored.chunk.chunk_id] = scored
        except TypeError:  # ctx was not iterable -- treat it as absent rather than fail
            supplied = {}

    resolved: list[ScoredChunk] = []
    missing: list[str] = []
    for chunk_id in chunk_ids:
        scored = supplied.get(chunk_id) or _REGISTRY.get(chunk_id)
        if scored is None:
            missing.append(chunk_id)
        else:
            resolved.append(scored)

    if not resolved:
        raise ToolInputError(
            "answer",
            f"none of the {len(chunk_ids)} chunk_ids resolve to a retrieved chunk; "
            "call retrieve first and pass the ids it returned",
            missing=missing[:8],
        )
    if missing:
        _LOG.debug("answer: %d unresolvable chunk_ids dropped", len(missing))
    return resolved


def _lead(text: str, max_chars: int) -> str:
    """The leading sentence(s) of `text`, cut at a real boundary within `max_chars`.

    Cutting mid-sentence produces an answer that reads as truncated, and truncation is
    indistinguishable from a model losing its train of thought -- exactly the impression a
    grounded extractive answer must not give.
    """
    stripped = text.strip()
    if len(stripped) <= max_chars:
        return stripped
    window = stripped[:max_chars]
    cut = max(window.rfind(ch) for ch in _TERMINATORS)
    if cut < max_chars // 3:  # no usable boundary: fall back to the last word break
        cut = window.rfind(" ")
    if cut <= 0:
        return window.rstrip()  # a script with no spaces (or one very long token)
    return window[: cut + 1].strip()


def _extractive_answer(query: str, context: Sequence[ScoredChunk], lang: Lang | None) -> Answer:
    """The harness's own last-resort generator: quote the best passage.

    Grounded by construction -- the answer text is a verbatim substring of the cited chunk,
    so `groundedness=1.0` is a fact rather than an estimate. This exists so that "the
    generator is down" degrades to a worse answer instead of to no answer.
    """
    if not context:
        return _refusal(RefusalReason.NO_RELEVANT_CONTEXT, lang)

    best = context[0]
    source = best.chunk.generation_text
    snippet = _lead(source, EXTRACTIVE_MAX_CHARS)
    if not snippet:
        return _refusal(RefusalReason.NO_RELEVANT_CONTEXT, lang)

    start = max(0, source.find(snippet))
    return Answer(
        text=snippet,
        mode=GenerationMode.FAST,
        citations=[
            Citation(
                chunk_id=best.chunk.chunk_id,
                doc_id=best.chunk.doc_id,
                answer_start=0,
                answer_end=len(snippet),
                source_start=start,
                source_end=start + len(snippet),
                quote=snippet,
            )
        ],
        groundedness=1.0,
        model=EXTRACTIVE_MODEL,
        lang=lang or best.chunk.lang,
    )


def _refusal(reason: RefusalReason, lang: Lang | None) -> Answer:
    return Answer(
        text=REFUSAL_TEXT.get(reason, settings.refusal_message),
        mode=GenerationMode.FAST,
        groundedness=0.0,
        refused=True,
        refusal_reason=reason,
        model="harness",
        lang=lang,
    )


async def _handle_answer(payload: AnswerInput, trace: Trace, ctx: Any) -> Answer:
    context = _resolve_chunks(payload.chunk_ids, ctx)
    mode = payload.mode

    try:
        generator = await _generator(mode)
    except Exception as exc:
        if mode is not GenerationMode.FAST:
            # Let the orchestrator decide: its policy is QUALITY -> FAST, and FAST has a
            # local fallback below, so escalating here still ends in an answer.
            raise
        trace.degrade(f"no {mode.value} generator ({type(exc).__name__}); extractive fallback")
        return _extractive_answer(payload.query, context, payload.lang)

    async def invoke() -> Answer:
        out = await generator.generate(payload.query, context, lang=payload.lang)
        if not isinstance(out, Answer) or not out.text.strip():
            # An empty string is a failed generation wearing a success's clothes. Raising it
            # here, inside the guarded call, is what makes the breaker count it.
            raise ProviderError(
                f"generate:{mode.value}",
                f"generator returned no usable answer ({type(out).__name__})",
            )
        return out

    # A breaker only earns its keep in front of a *remote* dependency, where failing fast
    # saves a network round trip. QUALITY talks to a model server, so it gets one. FAST is an
    # in-process extractive generator: a run of failures there is a bug in one branch of it,
    # not an outage, and tripping a breaker would disable a working generator for every
    # subsequent query -- turning a per-request degradation into a global one.
    invoke_guarded = (
        (lambda: get_breaker("generate:quality").call(invoke))
        if mode is not GenerationMode.FAST
        else invoke
    )
    try:
        answer = await invoke_guarded()
    except Exception as exc:
        if mode is not GenerationMode.FAST:
            raise
        trace.degrade(f"{mode.value} generation failed ({type(exc).__name__}); extractive fallback")
        return _extractive_answer(payload.query, context, payload.lang)

    if not answer.model:
        answer = answer.model_copy(update={"model": getattr(generator, "name", mode.value)})
    return answer


async def _handle_clarify(payload: ClarifyInput, trace: Trace, ctx: Any) -> Answer:
    answer = _refusal(payload.reason, payload.lang)
    return answer.model_copy(update={"text": CLARIFY_MESSAGE})


async def _handle_refuse(payload: RefuseInput, trace: Trace, ctx: Any) -> Answer:
    return _refusal(payload.reason, payload.lang)


