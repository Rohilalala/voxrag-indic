@dataclass(frozen=True)
class Tool:
    """One callable capability with a declared, enforced signature."""

    name: str
    description: str
    input_model: type[BaseModel]
    output_model: type[BaseModel]
    handler: Callable[[Any, Trace, Any], Awaitable[BaseModel]]
    #: Wall-clock ceiling for the handler. None means the caller owns the deadline.
    timeout_ms: float | None = None

    def schema(self) -> dict[str, Any]:
        """OpenAI/Ollama-style function schema, with the return shape attached.

        `parameters` is what a function-calling model is given; `returns` is what lets the
        same model plan a second call (retrieve -> read ids -> answer) instead of guessing.
        """
        return {
            "type": "function",
            "function": {
                "name": self.name,
                "description": self.description,
                "parameters": self.input_model.model_json_schema(),
                "returns": self.output_model.model_json_schema(),
            },
        }


#: retrieve spans embed + both arms. The arms overlap, so the ceiling is embed + the slower
#: arm + slack for fusion; it is a safety net over HybridRetriever's own per-arm deadlines,
#: not a target.
_RETRIEVE_TIMEOUT_MS: Final[float] = (
    stage_budget_ms(StageName.QUERY_EMBED)
    + max(stage_budget_ms(StageName.RETRIEVE_DENSE), stage_budget_ms(StageName.RETRIEVE_LEXICAL))
    + 25.0
)

