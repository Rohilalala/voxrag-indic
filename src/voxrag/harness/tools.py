# Chunk registry: makes id-addressed tool calls possible
# --------------------------------------------------------------------------------------


class _ChunkRegistry:
    """Bounded LRU of recently retrieved chunks, keyed by chunk_id.

    Thread-safe: uvicorn workers and `to_thread` retrieval callbacks both write to it.
    Bounded because it is a cache, and an unbounded one would hold every chunk the process
    has ever retrieved in memory for the lifetime of the server.
    """

    def __init__(self, maxsize: int) -> None:
        self._items: OrderedDict[str, ScoredChunk] = OrderedDict()
        self._maxsize = maxsize
        self._lock = threading.Lock()

    def put_many(self, chunks: Sequence[ScoredChunk]) -> None:
        if not chunks:
            return
        with self._lock:
            for scored in chunks:
                key = scored.chunk.chunk_id
                self._items[key] = scored
                self._items.move_to_end(key)
            while len(self._items) > self._maxsize:
                self._items.popitem(last=False)

    def get(self, chunk_id: str) -> ScoredChunk | None:
        with self._lock:
            scored = self._items.get(chunk_id)
            if scored is not None:
                self._items.move_to_end(chunk_id)
            return scored

    def __len__(self) -> int:
        with self._lock:
            return len(self._items)


_REGISTRY = _ChunkRegistry(CHUNK_REGISTRY_SIZE)


# --------------------------------------------------------------------------------------
# Lazily resolved, process-wide dependencies
# --------------------------------------------------------------------------------------

_EMBEDDER: Any | None = None
_EMBED_TASK: asyncio.Task[Any] | None = None
_EMBED_LOCK = asyncio.Lock()

_GENERATORS: dict[GenerationMode, Any] = {}
_GEN_LOCK = asyncio.Lock()


async def _embedder(*, wait: bool = True) -> Any | None:
    """The process-wide encoder, loaded once in a thread.

    The load reads an ONNX graph off disk and allocates its arenas -- hundreds of
    milliseconds, which is more than the entire request budget. Two properties follow:

    * `wait=False` returns None while a load is still in flight instead of blocking on it.
      That is what the request path passes: a cold start should degrade to lexical-only
      retrieval and answer, not spend the whole budget faulting a model in and then time out.
    * The load runs as one shared task and is awaited through `asyncio.shield`. A request
      that gives up (timeout, client disconnect) must not cancel the load itself, or every
      retry would restart it from scratch and no request would ever get an encoder.
    """
    global _EMBEDDER, _EMBED_TASK
    if _EMBEDDER is not None:
        return _EMBEDDER

    async with _EMBED_LOCK:
        if _EMBEDDER is not None:
            return _EMBEDDER
        task = _EMBED_TASK
        # Retry a load that failed: a missing model file can become a present one once a
        # download finishes, and permanently poisoning dense retrieval over one early miss
        # would be worse than paying for another attempt.
        if task is None or (task.done() and task.exception() is not None):
            from voxrag.embed import get_embedder

            task = _EMBED_TASK = asyncio.create_task(asyncio.to_thread(get_embedder))

    if not task.done() and not wait:
        return None
    _EMBEDDER = await asyncio.shield(task)
    return _EMBEDDER


def _resolve_generator_sync(mode: GenerationMode) -> Any:
    """Find a generator for `mode` in `voxrag.generate`. Runs in a thread: importing that
    module may open an HTTP client or probe a local model server."""
    try:
        import voxrag.generate as module
    except Exception as exc:  # module absent or failed to import
        raise ProviderError("generate", f"voxrag.generate unimportable: {exc!r}") from exc

    for attr in _GENERATOR_FACTORIES:
        factory = getattr(module, attr, None)
        if not callable(factory):
            continue
        # Default-arg binding, not closure capture: the lambdas must see *this* iteration's
        # factory even though the loop variable is about to be rebound.
        for call in (
            lambda f=factory: f(mode),
            lambda f=factory: f(mode=mode),
            lambda f=factory: f(),
        ):
            try:
                generator = call()
            except TypeError:
                # Signature mismatch -- try the next calling convention. A TypeError raised
                # *inside* the factory is misread as a mismatch here, which costs one extra
                # failed call and then surfaces as "no usable generator".
                continue
            except Exception as exc:
                raise ProviderError("generate", f"{attr}({mode.value}) failed: {exc!r}") from exc
            if generator is not None:
                return generator

    raise ProviderError(
        "generate",
        f"no usable factory for mode={mode.value}; tried {list(_GENERATOR_FACTORIES)}",
    )


async def _generator(mode: GenerationMode) -> Any:
    """Cached generator for `mode`. Holding it matters: the QUALITY path owns a pooled HTTP
    client to the model server, and rebuilding one per request would put a TCP handshake in
    front of every answer."""
    generator = _GENERATORS.get(mode)
    if generator is not None:
        return generator
    async with _GEN_LOCK:
        generator = _GENERATORS.get(mode)
        if generator is None:
            generator = await asyncio.to_thread(_resolve_generator_sync, mode)
            if inspect.isawaitable(generator):  # an async factory is a legal shape too
                generator = await generator
            if not hasattr(generator, "generate"):
                raise ProviderError(
                    "generate",
                    f"resolved object {type(generator).__name__} has no generate(); "
                    "it does not implement contracts.Generator",
                )
            _GENERATORS[mode] = generator
    return generator


def reset_dependencies() -> None:
    """Drop the cached embedder and generators. For tests and for a manual /health poke."""
    global _EMBEDDER, _EMBED_TASK
    _EMBEDDER = None
    _EMBED_TASK = None
    _GENERATORS.clear()


