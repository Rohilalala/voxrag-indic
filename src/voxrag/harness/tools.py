"""The tool layer: every pipeline capability behind one validated call boundary.

`call_tool(name, payload, trace)` validates the payload against the tool's declared
pydantic input model *before* dispatch and the handler's return against its output model
*after*, so nothing crosses a tool boundary unvalidated. That is not ceremony: the same
four tools are driven from three different places -- the orchestrator, the API, and (via
`tool_schemas()`) a gemma4 function-calling loop where the arguments are literally
generated by a language model. A model that emits `{"top_k": "twenty"}` must get a typed
error naming the field, not a TypeError three frames deeper inside numpy.

The four tools are the four things the system can actually do:

    retrieve(query, lang, top_k)      -> RetrievalResult
    answer(query, chunk_ids, mode)    -> Answer
    clarify(reason)                   -> Answer   (structured "I need more information")
    refuse(reason)                    -> Answer   (structured "I will not answer this")

`answer` takes chunk *ids* rather than chunk objects on purpose: it is the only shape a
function-calling model can produce. The ids resolve through the caller-supplied context
first and a bounded registry of recently retrieved chunks second, so a model can call
`retrieve`, read the ids back, pick three of them, and call `answer` -- without the
harness having to trust it to round-trip whole passages through a JSON payload.
"""

