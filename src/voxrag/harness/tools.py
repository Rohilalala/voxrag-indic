class RetrieveInput(BaseModel):
    """Arguments for `retrieve`. Bounds are enforced here so a model-generated payload
    cannot ask for 10_000 candidates and quietly eat the whole latency budget."""

    query: str = Field(min_length=1, max_length=settings.max_query_chars, description="The user question, in its original language and script.")
    lang: Lang | None = Field(default=None, description="Restrict retrieval to this language. Null searches every indexed language.")
    top_k: int = Field(default=settings.fuse_top_k, ge=1, le=100, description="How many fused candidates to return.")


class RetrievalResult(BaseModel):
    """Return value of `retrieve`."""

    chunks: list[ScoredChunk] = Field(default_factory=list)
    #: Evidence strength of the best hit in [0,1], comparable against
    #: `settings.min_retrieval_score`. See `store.hybrid.normalized_confidence`.
    confidence: float = 0.0
    n_candidates: int = 0
    #: True when one retrieval arm was unavailable and the result came from the other alone.
    degraded: bool = False
    note: str = ""

    @property
    def chunk_ids(self) -> list[str]:
        return [sc.chunk.chunk_id for sc in self.chunks]


class AnswerInput(BaseModel):
    """Arguments for `answer`. `chunk_ids` must reference chunks a previous `retrieve`
    returned -- generation without retrieved context is exactly the hallucination this
    system is built to prevent, so the model forbids it structurally."""

    query: str = Field(min_length=1, max_length=settings.max_query_chars)
    chunk_ids: list[str] = Field(min_length=1, max_length=32, description="Ids from a previous retrieve call, best first.")
    mode: GenerationMode = Field(default=settings.default_mode, description="fast = extractive and deterministic; quality = abstractive via the local model.")
    lang: Lang | None = Field(default=None, description="Language the answer must be written in.")


class ClarifyInput(BaseModel):
    """Arguments for `clarify` -- a structured 'I need more information' turn."""

    reason: RefusalReason = RefusalReason.LOW_CONFIDENCE
    #: Internal explanation for the trace. Never shown to the user verbatim.
    detail: str = ""
    lang: Lang | None = None


class RefuseInput(BaseModel):
    """Arguments for `refuse` -- a structured decline, with the reason on the record."""

    reason: RefusalReason
    detail: str = ""
    lang: Lang | None = None


